package io.github.agentic.ai.graph.agent.result;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

import com.networknt.schema.Error;
import com.networknt.schema.Schema;
import com.networknt.schema.SchemaRegistry;
import com.networknt.schema.SpecificationVersion;
import org.springframework.util.StringUtils;

import io.github.agentic.ai.api.chat.ChatClient;
import io.github.agentic.ai.api.chat.ChatMessage;
import io.github.agentic.ai.api.chat.ChatRequest;
import io.github.agentic.ai.api.chat.ChatResponse;
import io.github.agentic.ai.api.chat.ChatRole;
import io.github.agentic.ai.api.chat.GenerationOptions;
import io.github.agentic.ai.api.chat.ToolChoice;
import io.github.agentic.ai.api.chat.Usage;
import io.github.agentic.ai.graph.agent.AgentResult;
import tools.jackson.core.StreamReadFeature;
import tools.jackson.databind.DeserializationFeature;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * Turns the terminal assistant message of a run into an {@link AgentResult} by parsing
 * and schema-validating the configured output schema. This is the single delivery
 * boundary shared by every termination path (normal final message, returnDirect
 * synthesis, hook {@code JumpTo.end}): the terminal message itself is carried through
 * unchanged and never regenerated by the validation itself.
 *
 * <p>
 * Prompt-level schema constraints do not count as validation: without this component
 * the output of a run is unverified text. When no output schema is configured, the
 * result is {@link AgentResult.Status#COMPLETED} with no data — configuring a schema
 * signals the validation intent, calling {@code callResult} signals the delivery
 * intent (double opt-in, so the legacy {@code call} behavior never changes).
 * </p>
 *
 * <p>
 * The component never throws: every failure mode (malformed JSON, malformed schema,
 * schema violations) becomes {@link AgentResult.Status#VALIDATION_FAILED} with issue
 * entries that do not echo the full output content.
 * </p>
 *
 * <p>
 * When constructed with a {@link ChatClient}, a failed validation gets exactly one
 * bounded repair attempt: a single-turn model re-ask that carries no tools (and never
 * touches the graph), after which the repaired output is re-validated without a second
 * repair. A failed repair is marked with {@link #ERROR_CODE_REPAIRED_STILL_INVALID};
 * a failing repair client leaves the original failure untouched.
 * </p>
 */
public final class StructuredOutputFinalizer {

	private static final JsonMapper MAPPER = JsonMapper.builder()
		.enable(StreamReadFeature.STRICT_DUPLICATE_DETECTION)
		.enable(DeserializationFeature.FAIL_ON_TRAILING_TOKENS)
		.build();

	private static final SchemaRegistry SCHEMAS = SchemaRegistry.withDefaultDialect(SpecificationVersion.DRAFT_2020_12);

	private static final String ROOT_PATH = "$";

	private final ChatClient repairClient;

	/** Creates a pure validating finalizer without repair capability. */
	public StructuredOutputFinalizer() {
		this(null);
	}

	/**
	 * Creates a finalizer that performs one bounded repair re-ask through the given
	 * client when validation fails.
	 * @param repairClient the client used for the single repair re-ask; the request
	 * carries no tools and never touches the graph
	 */
	public StructuredOutputFinalizer(ChatClient repairClient) {
		this.repairClient = repairClient;
	}

	/**
	 * Finalizes the terminal message of a run against the configured output schema.
	 * @param terminal the terminal assistant message; must not be {@code null}
	 * @param outputSchema the configured JSON Schema for the output, or {@code null} or
	 * blank when the run has none
	 * @param usage the token usage recorded for the run, or {@code null} when unknown
	 * @return the delivery result; never {@code null} and never thrown over
	 */
	public AgentResult finalizeOutput(ChatMessage terminal, String outputSchema, Usage usage) {
		if (!StringUtils.hasLength(outputSchema)) {
			return AgentResult.completed(terminal, usage, null);
		}

		Schema schema;
		try {
			schema = SCHEMAS.getSchema(outputSchema);
		}
		catch (RuntimeException ex) {
			return AgentResult.validationFailed(terminal, usage,
					List.of(new AgentResult.OutputValidationIssue(AgentResult.ERROR_CODE_SCHEMA_MALFORMED,
							ROOT_PATH, "Configured output schema is not a valid JSON Schema")));
		}

		AgentResult first = validateAgainst(terminal, schema, usage);
		if (first.status() != AgentResult.Status.VALIDATION_FAILED || this.repairClient == null) {
			return first;
		}

		ChatMessage repaired = attemptRepair(terminal, outputSchema, first.issues());
		if (repaired == null) {
			// The repair client failed: keep the original failure untouched.
			return first;
		}
		AgentResult second = validateAgainst(repaired, schema, usage);
		if (second.status() != AgentResult.Status.VALIDATION_FAILED) {
			return second;
		}
		List<AgentResult.OutputValidationIssue> marked = new ArrayList<>();
		marked.add(new AgentResult.OutputValidationIssue(AgentResult.ERROR_CODE_REPAIRED_STILL_INVALID, ROOT_PATH,
				"One bounded repair attempt did not produce a schema-valid output"));
		marked.addAll(second.issues());
		return AgentResult.validationFailed(repaired, usage, List.copyOf(marked));
	}

	private AgentResult validateAgainst(ChatMessage terminal, Schema schema, Usage usage) {
		JsonNode root;
		try {
			root = MAPPER.readTree(terminal.text());
		}
		catch (RuntimeException ex) {
			return AgentResult.validationFailed(terminal, usage,
					List.of(new AgentResult.OutputValidationIssue(AgentResult.ERROR_CODE_INVALID_JSON, ROOT_PATH,
							"Terminal output is not valid JSON")));
		}

		List<Error> errors = schema.validate(root);
		if (!errors.isEmpty()) {
			List<AgentResult.OutputValidationIssue> issues = new ArrayList<>();
			for (Error error : errors) {
				issues.add(new AgentResult.OutputValidationIssue(AgentResult.ERROR_CODE_SCHEMA_VIOLATION,
						error.getInstanceLocation().toString(), error.getMessage()));
			}
			return AgentResult.validationFailed(terminal, usage, List.copyOf(issues));
		}

		return AgentResult.completed(terminal, usage, root);
	}

	/**
	 * One bounded repair re-ask: single-turn, no tools, no graph. Returns the repaired
	 * assistant message, or {@code null} when the repair client itself failed.
	 */
	private ChatMessage attemptRepair(ChatMessage terminal, String outputSchema,
			List<AgentResult.OutputValidationIssue> issues) {
		try {
			String issueSummary = issues.stream()
				.map(issue -> issue.errorCode()
						+ (StringUtils.hasLength(issue.fieldPath()) && !ROOT_PATH.equals(issue.fieldPath())
								? " at " + issue.fieldPath() : ""))
				.collect(Collectors.joining("; "));
			ChatMessage system = ChatMessage
				.system("Return only valid JSON matching this JSON Schema without any surrounding text: "
						+ outputSchema);
			ChatMessage user = ChatMessage.user("The previous response failed schema validation (" + issueSummary
					+ "). Return the corrected JSON only.\nPrevious response:\n" + terminal.text());
			ChatResponse response = this.repairClient.callBlocking(new ChatRequest(List.of(system, user), List.of(),
					GenerationOptions.builder().toolChoice(ToolChoice.none()).build(), Map.of()));
			return response.messages().stream()
				.filter(message -> message.role() == ChatRole.ASSISTANT)
				.findFirst()
				.orElse(null);
		}
		catch (RuntimeException ex) {
			return null;
		}
	}

}
