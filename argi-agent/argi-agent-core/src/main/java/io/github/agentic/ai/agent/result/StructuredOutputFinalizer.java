/**
 * Turns the terminal assistant message of a run into an {@link AgentResult} by parsing
 * and schema-validating the configured output schema. This is the single delivery
 * boundary shared by every termination path (normal final message, returnDirect
 * synthesis, hook {@code JumpTo.end}): the terminal message itself is carried through
 * unchanged and never regenerated by the validation itself.
 *
 * <p>
 * Prompt-level schema constraints do not count as validation: without this component
 * the output of a run is unverified text. When no output schema is configured, the
 * result is {@link AgentResult.Status#COMPLETED} with no data — configuring a schema
 * signals the validation intent, calling {@code callResult} signals the delivery
 * intent (double opt-in, so the legacy {@code call} behavior never changes).
 * </p>
 *
 * <p>
 * Validation never throws: every output failure mode (malformed JSON, malformed
 * schema, schema violations) becomes {@link AgentResult.Status#VALIDATION_FAILED} with
 * issue entries that do not echo the full output content.
 * </p>
 *
 * <p>
 * When constructed with a {@link ChatClient}, a failed validation gets exactly one
 * bounded repair attempt: a single-turn model re-ask that carries no tools (and never
 * touches the graph), after which the repaired output is re-validated without a second
 * repair. A repair that still fails validation is marked with
 * {@link AgentResult#ERROR_CODE_REPAIRED_STILL_INVALID}; a repair re-ask that cannot
 * be performed is marked with {@link AgentResult#ERROR_CODE_REPAIR_CALL_FAILED} beside
 * the original failure.
 * </p>
 *
 * <p>
 * Passing the run's {@link ExecutionGuard} makes the repair re-ask execution-aware:
 * a guard that is already stopped (cancelled, past its deadline, ownership lost)
 * skips the re-ask and propagates the stop instead of returning a validation failure,
 * and a stop raised while the re-ask is in flight cancels that call and propagates
 * the stop. A deadline carried by the guard is enforced while the response is still
 * pending — a request that never returns is cancelled once the deadline expires —
 * and a deadline that expires after the response returned still stops the delivery
 * before publishing it. Without a guard, a cancelled or failing repair client
 * degrades to the marked repair failure instead.
 * </p>
 */
public final class StructuredOutputFinalizer {

	private static final JsonMapper MAPPER = JsonMapper.builder()
		.enable(StreamReadFeature.STRICT_DUPLICATE_DETECTION)
		.enable(DeserializationFeature.FAIL_ON_TRAILING_TOKENS)
		.build();

	private static final SchemaRegistry SCHEMAS = SchemaRegistry.withDefaultDialect(SpecificationVersion.DRAFT_2020_12);

	private static final String ROOT_PATH = "$";

	/**
	 * The in-flight repair re-ask is awaited in slices of this length so the run's
	 * synchronous deadline boundary is enforced while the response is still pending;
	 * an expired deadline cancels the underlying call within one slice.
	 */
	private static final long DEADLINE_POLL_MILLIS = 25L;

	private final ChatClient repairClient;

	/** Creates a pure validating finalizer without repair capability. */
	public StructuredOutputFinalizer() {
		this(null);
	}

	/**
	 * Creates a finalizer that performs one bounded repair re-ask through the given
	 * client when validation fails.
	 * @param repairClient the client used for the single repair re-ask; the request
	 * carries no tools and never touches the graph
	 */
	public StructuredOutputFinalizer(ChatClient repairClient) {
		this.repairClient = repairClient;
	}

	/**
	 * Finalizes the terminal message of a run against the configured output schema.
	 * @param terminal the terminal assistant message; must not be {@code null}
	 * @param outputSchema the configured JSON Schema for the output, or {@code null} or
	 * blank when the run has none
	 * @param usage the token usage recorded for the run, or {@code null} when unknown
	 * @return the delivery result; never {@code null} and never thrown over
	 */
	public AgentResult finalizeOutput(ChatMessage terminal, String outputSchema, Usage usage) {
		return finalizeOutput(terminal, outputSchema, usage, null);
	}

	/**
	 * Finalizes the terminal message of a run against the configured output schema under
	 * the run's execution guard. The guard governs the optional repair re-ask: a guard
	 * that is already stopped (cancelled, past its deadline, ownership lost) skips the
	 * re-ask and propagates the stop instead of returning a validation failure, and a
	 * stop raised while the re-ask is in flight cancels that call and propagates the
	 * stop. A deadline carried by the guard is enforced while the response is still
	 * pending — a request that never returns is cancelled once the deadline expires —
	 * and a deadline that expires after the response returned still stops the delivery
	 * before publishing it. Validation failures themselves are never thrown. Without a
	 * guard, a cancelled or failing repair client degrades to a marked repair failure
	 * instead.
	 * @param terminal the terminal assistant message; must not be {@code null}
	 * @param outputSchema the configured JSON Schema for the output, or {@code null} or
	 * blank when the run has none
	 * @param usage the token usage recorded for the run, or {@code null} when unknown
	 * @param control the run's execution guard, or {@code null} to keep the
	 * uncontrolled legacy behavior
	 * @return the delivery result; never {@code null} and never thrown over
	 */
	public AgentResult finalizeOutput(ChatMessage terminal, String outputSchema, Usage usage, ExecutionGuard control) {
		if (outputSchema == null || outputSchema.isEmpty()) {
			return AgentResult.completed(terminal, usage, null);
		}

		Schema schema;
		try {
			schema = SCHEMAS.getSchema(outputSchema);
		}
		catch (RuntimeException ex) {
			return AgentResult.validationFailed(terminal, usage,
					List.of(new AgentResult.OutputValidationIssue(AgentResult.ERROR_CODE_SCHEMA_MALFORMED,
							ROOT_PATH, "Configured output schema is not a valid JSON Schema")));
		}

		AgentResult first = validateAgainst(terminal, schema, usage);
		if (first.status() != AgentResult.Status.VALIDATION_FAILED || this.repairClient == null) {
			return first;
		}
		if (control != null) {
			// A stopped run must not spend another model call: cancelled, deadline
			// exceeded and ownership lost all propagate as execution stops.
			control.assertActive();
		}
		ChatMessage repaired = attemptRepair(terminal, outputSchema, first.issues(), control);
		if (repaired == null) {
			// The repair re-ask could not be performed: keep the original failure and
			// mark the distinction from a repair that ran but stayed invalid.
			List<AgentResult.OutputValidationIssue> marked = new ArrayList<>();
			marked.add(new AgentResult.OutputValidationIssue(AgentResult.ERROR_CODE_REPAIR_CALL_FAILED, ROOT_PATH,
					"The bounded repair re-ask could not be performed or returned no assistant message"));
			marked.addAll(first.issues());
			return AgentResult.validationFailed(first.message(), first.usage(), List.copyOf(marked));
		}
		if (control != null) {
			// Deadline checks are synchronous: a deadline that expired during the
			// re-ask stops the delivery here instead of publishing a late output.
			control.assertActive();
		}
		AgentResult second = validateAgainst(repaired, schema, usage);
		if (second.status() != AgentResult.Status.VALIDATION_FAILED) {
			return second;
		}
		List<AgentResult.OutputValidationIssue> marked = new ArrayList<>();
		marked.add(new AgentResult.OutputValidationIssue(AgentResult.ERROR_CODE_REPAIRED_STILL_INVALID, ROOT_PATH,
				"One bounded repair attempt did not produce a schema-valid output"));
		marked.addAll(second.issues());
		return AgentResult.validationFailed(repaired, usage, List.copyOf(marked));
	}

	private AgentResult validateAgainst(ChatMessage terminal, Schema schema, Usage usage) {
		JsonNode root;
		try {
			root = MAPPER.readTree(terminal.text());
		}
		catch (RuntimeException ex) {
			return AgentResult.validationFailed(terminal, usage,
					List.of(new AgentResult.OutputValidationIssue(AgentResult.ERROR_CODE_INVALID_JSON, ROOT_PATH,
							"Terminal output is not valid JSON")));
		}

		List<Error> errors = schema.validate(root);
		if (!errors.isEmpty()) {
			List<AgentResult.OutputValidationIssue> issues = new ArrayList<>();
			for (Error error : errors) {
				issues.add(new AgentResult.OutputValidationIssue(AgentResult.ERROR_CODE_SCHEMA_VIOLATION,
						error.getInstanceLocation().toString(), error.getMessage()));
			}
			return AgentResult.validationFailed(terminal, usage, List.copyOf(issues));
		}

		return AgentResult.completed(terminal, usage, root);
	}

	/**
	 * One bounded repair re-ask: single-turn, no tools, no graph. Returns the repaired
	 * assistant message, or {@code null} when the repair client itself failed.
	 */
	private ChatMessage attemptRepair(ChatMessage terminal, String outputSchema,
			List<AgentResult.OutputValidationIssue> issues, ExecutionGuard control) {
		try {
			String issueSummary = issues.stream()
				.map(issue -> issue.errorCode()
						+ (issue.fieldPath() != null && !issue.fieldPath().isEmpty() && !ROOT_PATH.equals(issue.fieldPath())
								? " at " + issue.fieldPath() : ""))
				.collect(Collectors.joining("; "));
			ChatMessage system = ChatMessage
				.system("Return only valid JSON matching this JSON Schema without any surrounding text: "
						+ outputSchema);
			ChatMessage user = ChatMessage.user("The previous response failed schema validation (" + issueSummary
					+ "). Return the corrected JSON only.\nPrevious response:\n" + terminal.text());
			ChatRequest request = new ChatRequest(List.of(system, user), List.of(),
					GenerationOptions.builder().toolChoice(ToolChoice.none()).build(), Map.of());
			ChatResponse response = control == null ? this.repairClient.callBlocking(request)
					: callUnderControl(request, control);
			return response.messages().stream()
				.filter(message -> message.role() == ChatRole.ASSISTANT)
				.findFirst()
				.orElse(null);
		}
		catch (CancellationException cancelled) {
			if (control == null) {
				// The uncontrolled path has no stop semantics to preserve.
				return null;
			}
			// Propagate the control's stop reason when the cancellation came from it;
			// a cancellation raised by the client itself stays a cancellation.
			control.assertActive();
			throw cancelled;
		}
		catch (RuntimeException ex) {
			if (control != null) {
				// A stop-shaped failure (a guard whose assertActive throws a plain
				// RuntimeException, such as a lost checkpoint lease) must propagate as
				// that stop instead of degrading to a marked repair failure; an active
				// guard confirms the failure was the client's own.
				control.assertActive();
			}
			return null;
		}
	}

	/**
	 * Performs the repair re-ask bound to the run's guard: a stop raised while the call
	 * is in flight cancels the pending call, and the cancellation observed while waiting
	 * is translated back into the guard's stop by the caller. When the guard carries a
	 * deadline the wait is sliced so the synchronous deadline boundary is enforced while
	 * the response is still pending — a request that never returns is cancelled once the
	 * deadline expires instead of blocking the delivery. A guard without a deadline is
	 * waited on plainly: every stop path fires the onLoss registration synchronously,
	 * and slicing would only add idle wakeups.
	 */
	private ChatResponse callUnderControl(ChatRequest request, ExecutionGuard control) {
		CompletableFuture<ChatResponse> pending = this.repairClient.call(request).toCompletableFuture();
		AtomicReference<Throwable> failure = new AtomicReference<>();
		pending.whenComplete((response, error) -> {
			if (error != null) {
				failure.set(error);
			}
		});
		try (AutoCloseable ignored = control.onLoss(() -> pending.cancel(true))) {
			if (control.deadline().isEmpty()) {
				return pending.get();
			}
			while (true) {
				try {
					return pending.get(DEADLINE_POLL_MILLIS, TimeUnit.MILLISECONDS);
				}
				catch (TimeoutException notYet) {
					// Deadline checks are synchronous on the guard: a deadline that
					// expires stops the run here, and the stop invokes the onLoss
					// registration above, cancelling the underlying in-flight call.
					control.assertActive();
				}
			}
		}
		catch (InterruptedException interrupted) {
			pending.cancel(true);
			Thread.currentThread().interrupt();
			throw new CancellationException("Model repair call interrupted");
		}
		catch (CancellationException cancelled) {
			if (failure.get() instanceof CancellationException original) {
				throw original;
			}
			throw cancelled;
		}
		catch (Exception error) {
			// onLoss detachment cannot fail; everything else reaching here is the
			// awaited call failure, unwrapped from its ExecutionException carrier.
			throw repairFailure(error instanceof ExecutionException execution ? execution.getCause() : error);
		}
	}

	private static RuntimeException repairFailure(Throwable error) {
		if (error instanceof RuntimeException runtime) {
			return runtime;
		}
		if (error instanceof java.lang.Error fatal) {
			throw fatal;
		}
		return new IllegalStateException("Model repair call failed", error);
	}

}
